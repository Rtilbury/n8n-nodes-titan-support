const fs = require('node:fs');
const path = require('node:path');
const Ajv2020 = require('ajv/dist/2020').default;
const addFormats = require('ajv-formats');
const standaloneCode = require('ajv/dist/standalone').default;

const schemaPath = path.join(
  __dirname, '..', 'schemas', 'titan-canonical-response.schema.json'
);
const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));

const ajv = new Ajv2020({
  strict: true,
  validateFormats: true,
  code: { source: true, esm: false },
});

addFormats(ajv);

const validate = ajv.compile(schema);
const generated = standaloneCode(ajv, validate);

const outputPath = path.join(
  __dirname, '..', 'dist', 'canonical-standalone-probe.cjs'
);

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, generated, 'utf8');

const standaloneValidate = require(outputPath);

const invalid = {
  identity: null,
  intelligence: null,
  recovery: null,
  governance: null,
  telemetry: null,
};

if (validate(invalid) !== false || standaloneValidate(invalid) !== false) {
  throw new Error('Standalone validator failed the rejection probe');
}

const imports = [...new Set(
  generated.match(/require\s*\(\s*["'][^"']+["']\s*\)/g) || []
)];

console.log('Standalone generation: SUCCESS');
console.log('Generated bytes:', Buffer.byteLength(generated));
console.log('Rejects invalid nested response: YES');
console.log('Generated runtime require statements:');
if (imports.length === 0) {
  console.log('NONE');
} else {
  for (const item of imports) {
    console.log('  ' + item);
  }
}
console.log('Generated file:', outputPath);
